"""With HARNESS_BLOCK_AI_TRAILERS on, only trailer and footer lines count as attribution."""

import subprocess

import pytest

AI_ENV = {"HARNESS_BLOCK_AI_TRAILERS": "1"}
TRAILER_BLOCKED = "git commit -m 'feat: x' -m 'Co-Authored-By: Claude <noreply@anthropic.com>'"


@pytest.fixture
def feature_repo(git_repo):
    subprocess.run(["git", "-C", str(git_repo), "checkout", "-q", "-b", "feature/x"], check=True)
    return git_repo


def run(hook, repo, command, env=None):
    return hook("commit_guard.py", command, cwd=str(repo), env=env)


@pytest.mark.parametrize(
    "command",
    [
        "git commit -m 'docs: explain the Claude Code hooks'",
        "git commit -m 'docs: update claude.ai links'",
        "echo 'Claude Code' && git commit -m 'feat: x'",
        "git commit -m 'feat: x' -m 'Co-Authored-By: Jane Doe <jane@example.com>'",
        "git commit -m 'feat: x' -m 'Claude Code reviewed the parser change.'",
    ],
)
def test_mentioning_an_assistant_is_not_an_attribution(hook, feature_repo, command):
    result = run(hook, feature_repo, command, env=AI_ENV)
    assert result.returncode == 0, result.stderr


@pytest.mark.parametrize(
    "command",
    [
        TRAILER_BLOCKED,
        "git commit -m 'feat: x' -m 'Generated with [Claude Code](https://claude.ai/code)'",
        "git commit -m 'feat: x' -m '🤖 Generated by a tool'",
        "git commit -m 'feat: x' -m 'Assisted-by: Copilot'",
        "git commit -m \"$(cat <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude\nEOF\n)\"",
    ],
)
def test_attribution_lines_are_blocked_when_enabled(hook, feature_repo, command):
    result = run(hook, feature_repo, command, env=AI_ENV)
    assert result.returncode == 2
    assert "AI attribution" in result.stderr


def test_attribution_lines_are_allowed_when_disabled(hook, feature_repo):
    assert run(hook, feature_repo, TRAILER_BLOCKED).returncode == 0
